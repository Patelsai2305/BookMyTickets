<script type="module">
    import { db, onSnapshot, collection, query, where } from './js/firebase-config.js';

    const params = new URLSearchParams(window.location.search);
    const movieId = params.get('movieId');
    const theatreId = params.get('theatreId');
    const date = params.get('date');
    const timing = params.get('timing');

    const grid = document.getElementById('seats-grid');
    const rows = ['A', 'B', 'C', 'D', 'E', 'F'];
    let selectedSeats = [];

    // 1. Generate Grid
    function renderGrid(bookedSeats = []) {
        grid.innerHTML = '';
        rows.forEach(row => {
            for (let i = 1; i <= 8; i++) {
                const seatId = `${row}${i}`;
                const isBooked = bookedSeats.includes(seatId);
                const type = (row === 'A' || row === 'B') ? 'VIP' : (row === 'C' || row === 'D') ? 'Premium' : 'Normal';
                const price = (type === 'VIP') ? 450 : (type === 'Premium') ? 300 : 200;

                const seatDiv = document.createElement('div');
                seatDiv.className = `seat ${type.toLowerCase()} ${isBooked ? 'booked' : ''}`;
                seatDiv.innerText = seatId;

                if (!isBooked) {
                    seatDiv.onclick = () => toggleSeat(seatId, price, seatDiv);
                }
                grid.appendChild(seatDiv);
            }
        });
    }

    function toggleSeat(id, price, element) {
        const index = selectedSeats.findIndex(s => s.id === id);
        if (index > -1) {
            selectedSeats.splice(index, 1);
            element.classList.remove('selected');
        } else {
            selectedSeats.push({ id, price });
            element.classList.add('selected');
        }
        updateSummary();
    }

    function updateSummary() {
        document.getElementById('selected-list').innerText = selectedSeats.map(s => s.id).join(', ') || 'None';
        const total = selectedSeats.reduce((sum, s) => sum + s.price, 0);
        document.getElementById('total-price').innerText = `₹ ${total}`;
    }

    // 2. Real-time Sync (Android & Web)
    if (movieId && theatreId && date && timing) {
        const q = query(collection(db, "Bookings"),
            where("movieId", "==", movieId),
            where("theatreId", "==", theatreId),
            where("date", "==", date),
            where("timing", "==", timing),
            where("status", "!=", "Cancelled")
        );

        onSnapshot(q, (snapshot) => {
            const booked = [];
            snapshot.forEach(doc => {
                const data = doc.data();
                if (data.seats) booked.push(...data.seats);
            });
            renderGrid(booked);
        });
    } else {
        renderGrid();
    }

    // 3. Move to Payment (Does NOT save to DB yet)
    document.getElementById('btn-confirm').onclick = () => {
        if (selectedSeats.length === 0) return alert("Select at least one seat");

        const seatIds = selectedSeats.map(s => s.id).join(',');
        const totalPrice = selectedSeats.reduce((sum, s) => sum + s.price, 0);

        const url = `payment.php?${params.toString()}&seats=${seatIds}&totalPrice=${totalPrice}`;
        window.location.href = url;
    };
</script>

